import asyncio
import os
import sys
from collections.abc import AsyncIterator
from pathlib import Path
from typing import Any, ClassVar, Dict, Mapping, Optional, Sequence, Tuple

import numpy as np
from typing_extensions import Self
from viam.components import KinematicsReturn
from viam.components.arm import Arm as ArmBase
from viam.components.arm import JointPositions, Mesh, MoveOptions, Pose
from viam.proto.app.robot import ComponentConfig
from viam.proto.common import Geometry, KinematicsFileFormat, ResourceName
from viam.resource.base import ResourceBase
from viam.resource.easy_resource import EasyResource
from viam.resource.types import Model, ModelFamily
from viam.utils import ValueTypes, struct_to_dict

from . import vega

COMPONENTS = ("left_arm", "right_arm", "head", "torso")
# Generated by scripts/extract_kinematics.py; bundled into the PyInstaller binary by build.sh.
KINEMATICS_DIR = Path(getattr(sys, "_MEIPASS", Path(__file__).parents[2])) / "kinematics"
VARIANTS = sorted(p.name for p in KINEMATICS_DIR.iterdir() if p.is_dir()) if KINEMATICS_DIR.is_dir() else []

# ROBOT_NAME suffix -> variant. Never `_no_ft`: the F/T sensor isn't encoded in ROBOT_NAME.
SUFFIX_VARIANTS = {"1": "vega_1", "1p": "vega_1p", "1u": "vega_1u"}


def variant_from_robot_name() -> str | None:
    """Variant for ROBOT_NAME (`dm/vgXXXXXXXXXX-1p` -> `vega_1p`), or None if unset/unknown."""
    return SUFFIX_VARIANTS.get(os.environ.get("ROBOT_NAME", "").rpartition("-")[2])


class Arm(ArmBase, EasyResource):
    """One Vega joint group (left_arm, right_arm, head or torso) as a Viam arm.

    Moves go through dexcontrol's motion plugin (move_to_joint_pos), which
    smooths the trajectory on the robot. Viam joint units are degrees.
    """

    MODEL: ClassVar[Model] = Model(ModelFamily("viam", "viam-dexmate"), "arm")

    component: str
    kinematics_file: str | None
    velocity_scale: float | None
    _handle: Any = None

    @classmethod
    def new(cls, config: ComponentConfig, dependencies: Mapping[ResourceName, ResourceBase]) -> Self:
        arm = super().new(config, dependencies)
        arm.reconfigure(config, dependencies)
        vega.acquire()
        return arm

    @classmethod
    def validate_config(cls, config: ComponentConfig) -> Tuple[Sequence[str], Sequence[str]]:
        attrs = struct_to_dict(config.attributes)
        if attrs.get("component") not in COMPONENTS:
            raise ValueError(f"`component` must be one of {COMPONENTS}")
        variant = attrs.get("variant")
        if variant is None and not attrs.get("kinematics_file"):
            variant = variant_from_robot_name()
        if variant is not None and not (KINEMATICS_DIR / variant / f"{attrs['component']}.urdf").is_file():
            raise ValueError(f"no {attrs['component']} kinematics for variant {variant!r}; have {VARIANTS}")
        scale = attrs.get("velocity_scale")
        if scale is not None and not 0 < scale <= 1:
            raise ValueError("`velocity_scale` must be in (0, 1]")
        return [], []

    def reconfigure(self, config: ComponentConfig, dependencies: Mapping[ResourceName, ResourceBase]):
        attrs = struct_to_dict(config.attributes)
        self.component = attrs["component"]
        variant = attrs.get("variant") or variant_from_robot_name()
        self.kinematics_file = attrs.get("kinematics_file") or (
            str(KINEMATICS_DIR / variant / f"{self.component}.urdf") if variant else None
        )
        self.velocity_scale = attrs.get("velocity_scale")

    def _part(self):
        return getattr(vega.get(), self.component)

    async def get_joint_positions(self, *, extra=None, timeout=None, **kwargs) -> JointPositions:
        rad = await asyncio.to_thread(lambda: self._part().get_joint_pos())
        return JointPositions(values=np.degrees(rad).tolist())

    async def move_to_joint_positions(self, positions: JointPositions, *, extra=None, timeout=None, **kwargs):
        target = np.radians(list(positions.values))

        def move():
            self._handle = self._part().move_to_joint_pos(target, velocity_scale=self.velocity_scale)
            self._handle.wait(timeout)  # raises on plugin error/timeout

        await asyncio.to_thread(move)

    async def move_through_joint_positions(
        self, positions: list[JointPositions], options: MoveOptions | None = None, *, extra=None, timeout=None, **kwargs
    ):
        # ponytail: waypoint-by-waypoint (stops at each). Use dexcontrol's
        # move_joint_trajectory if smooth pass-through matters.
        for p in positions:
            await self.move_to_joint_positions(p, timeout=timeout)

    async def stop(self, *, extra=None, timeout=None, **kwargs):
        def halt():
            if self._handle is not None:
                self._handle.cancel()
            part = self._part()
            if hasattr(part, "stop"):  # head/torso hold position; arms have no stop()
                part.stop()

        await asyncio.to_thread(halt)

    async def is_moving(self) -> bool:
        return self._handle is not None and not self._handle.is_done

    async def get_kinematics(self, *, extra=None, timeout=None, **kwargs) -> KinematicsReturn:
        if not self.kinematics_file:
            raise ValueError(f"set `variant` (one of {VARIANTS}) or `kinematics_file`")
        with open(self.kinematics_file, "rb") as f:
            return KinematicsFileFormat.KINEMATICS_FILE_FORMAT_URDF, f.read()

    async def get_geometries(self, *, extra: Optional[Dict[str, Any]] = None, timeout: Optional[float] = None) -> Sequence[Geometry]:
        return []

    async def close(self):
        vega.release()

    # Cartesian moves: use the Viam motion service with `kinematics_file` set.
    async def get_end_position(self, *, extra=None, timeout=None, **kwargs) -> Pose:
        raise NotImplementedError("use the motion service / frame system")

    async def move_to_position(self, pose: Pose, *, extra=None, timeout=None, **kwargs):
        raise NotImplementedError("use the motion service")

    async def move_through_joint_positions_streamed(
        self, batches: AsyncIterator[list["ArmBase.TrajectoryPoint"]], *, extra=None, timeout=None, **kwargs
    ) -> AsyncIterator["ArmBase.TrajectoryUpdate"]:
        raise NotImplementedError()

    async def get_3d_models(self, *, extra=None, timeout=None, **kwargs) -> Mapping[str, Mesh]:
        return {}

    async def set_manual_mode(self, manual_mode: bool, enabled_for: int = 0, *, extra=None, timeout=None, **kwargs):
        raise NotImplementedError()

    async def get_manual_mode(self, *, extra=None, timeout=None, **kwargs) -> bool:
        return False

    async def get_properties(self, *, extra=None, timeout=None, **kwargs) -> ArmBase.Properties:
        raise NotImplementedError()

    async def do_command(self, command: Mapping[str, ValueTypes], *, timeout: Optional[float] = None, **kwargs) -> Mapping[str, ValueTypes]:
        raise NotImplementedError()

    async def get_status(self, *, timeout: Optional[float] = None, **kwargs) -> Mapping[str, ValueTypes]:
        raise NotImplementedError()
